"""
ArXiv论文总结提示词模板
包含用于AI生成论文总结的提示词模板
"""

class PromptTemplates:
    """提示词模板类"""
    
    @staticmethod
    def get_paper_summary_prompt(paper_content: str) -> str:
        """
        获取论文总结提示词
        
        Args:
            paper_content: 论文内容
            
        Returns:
            完整的提示词
        """
        prompt = f"""
请总结以上论文,要求按照以下要求进行总结，最后的结果以html格式呈现,不要输出无关的内容。语言为中文,页面应该简洁优美,内容需要尽可能的丰富饱满。
格式要求：
1. 结构清晰：按照论文背景、方法、实验和结论四部分组织内容
    a. 背景部分从"存在的问题"、"之前的方法以及不足"和"论文提出的方法以及贡献"三个方面进行分析
    b. 方法部分分析需要从论文提出的具体方法进行分析，最好分点进行分析
    c. 实验部分需要包含"实验设计"、"实验结果"以及"实验总结"等三个角度分析
    d. 结论部分主要是对于该论文进行总结。
2. 视觉美观：使用现代化CSS设计，包含渐变标题、卡片式布局和响应式设计
3. 第一张卡片为中文标题、作者、论文的链接和代码的链接，其中论文的链接和代码的链接是可以直接进行点击跳转的。
4. 第二张卡片为摘要卡片，附上完整的“中文”摘要，不要对于摘要进行总结。
5. 最后一张卡片应该写上关于论文方向的研究建议，在最底部加上"本报告来源于晓勇的论文智能助手"。
6. 内容完整：
    ○ 包含关键图表并放置在相关部分
    ○ 展示主要实验结果数据表格
    ○ 展示核心的公式并简单介绍
    ○ 详细说明创新方法
    ○ 重点内容需要加重显示
7. 响应式设计：适配不同屏幕尺寸的设备
8.请不要输出其他无关的内容，比如文件说明等


论文内容：
{paper_content}
"""
        return prompt
    
    @staticmethod
    def get_system_prompt() -> str:
        """
        获取系统提示词
        
        Returns:
            系统提示词
        """
        return "你是一个专业的学术论文总结助手。"
    
    @staticmethod
    def get_research_prompt(topic: str) -> str:
        """
        获取研究主题提示词
        
        Args:
            topic: 研究主题
            
        Returns:
            研究提示词
        """
        return f"""
请帮我分析关于"{topic}"的最新研究进展，包括：
1. 该领域的主要挑战和问题
2. 当前主流的解决方案
3. 最新的研究方向和趋势
4. 值得关注的研究机构和学者
""" 